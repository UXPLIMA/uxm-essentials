package com.uxplima.uxmessentials.api.view;

/** The postures a player can be put into by the poses module. */
public enum UxmPoseType {

    /** Sitting on a block. */
    SIT,

    /** Sitting on another player's shoulders. */
    PLAYER_SIT,

    /** Lying on the back. */
    LAY,

    /** Lying face down. */
    BELLYFLOP,

    /** Spinning on the spot. */
    SPIN,

    /** Crawling, as if under a one-block gap. */
    CRAWL
}
