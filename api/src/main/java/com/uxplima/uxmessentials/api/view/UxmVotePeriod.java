package com.uxplima.uxmessentials.api.view;

/** The window a vote leaderboard covers. */
public enum UxmVotePeriod {

    /** The server's current day. */
    DAILY,

    /** The current week. */
    WEEKLY,

    /** The current month. */
    MONTHLY,

    /** Every vote ever cast. */
    ALL_TIME
}
