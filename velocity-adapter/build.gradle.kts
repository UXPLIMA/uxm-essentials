plugins {
    id("uxm.java")
    id("com.gradleup.shadow")
}

// The optional proxy-side cross-server bus broker. It shares the pure NetworkMessage hierarchy and codec with
// the bukkit-side bus client through :core, compiles against velocity-api only, and ships as its own jar.

dependencies {
    implementation(project(":core"))
    api(project(":api"))
    compileOnly(libs.velocity.api)
    // The proxy provides Configurate, Adventure and LuckPerms at runtime.
    compileOnly(uxm.configurate.hocon)
    compileOnly(libs.bundles.adventure)
    compileOnly(libs.luckperms.api)
    annotationProcessor(libs.velocity.api)
}

// The velocity-api annotation processor generates its own velocity-plugin.json from the @Plugin annotation. The
// hand-written resource is authoritative, so the generated copy is dropped before it reaches the jar.
tasks.named<JavaCompile>("compileJava") {
    doLast {
        val generated = destinationDirectory.file("velocity-plugin.json").get().asFile
        if (generated.exists()) {
            generated.delete()
        }
    }
}

// Generate BuildConstants so the @Plugin(version = ...) annotation can reference a compile-time
// constant; the same project.version is expanded into velocity-plugin.json below.
val generatedSources = layout.buildDirectory.dir("generated/sources/buildconstants/java/main")

val generateBuildConstants by tasks.registering {
    val outputDir = generatedSources
    val pluginVersion = project.version.toString()
    inputs.property("version", pluginVersion)
    outputs.dir(outputDir)
    doLast {
        val pkgDir = outputDir.get().dir("com/uxplima/uxmessentials/velocity").asFile
        pkgDir.mkdirs()
        pkgDir.resolve("BuildConstants.java").writeText(
            """
            package com.uxplima.uxmessentials.velocity;

            /** Build-time constants surfaced to the {@code @Plugin} descriptor; generated by Gradle. */
            final class BuildConstants {

                /** The plugin version, expanded from the Gradle project version at build time. */
                static final String VERSION = "$pluginVersion";

                private BuildConstants() {}
            }
            """.trimIndent() + "\n",
        )
    }
}

sourceSets {
    main {
        java {
            // Wiring the source dir to the task lets Gradle infer the dependency for every consumer
            // (compileJava, sourcesJar, spotless) so none reads the generated file before it is written.
            srcDir(generateBuildConstants)
        }
    }
}

tasks.processResources {
    val props = mapOf("version" to project.version)
    inputs.properties(props)
    filesMatching("velocity-plugin.json") { expand(props) }
}

tasks.shadowJar {
    archiveBaseName = "uxmEssentials-velocity"
    archiveClassifier = ""
    mergeServiceFiles()
    dependencies {
        exclude(dependency("org.slf4j:.*:.*"))
        exclude(dependency("net.kyori:.*:.*"))
        exclude(dependency("com.velocitypowered:.*:.*"))
    }
}

tasks.jar { archiveClassifier = "thin" }

tasks.assemble { dependsOn(tasks.shadowJar) }

spotless {
    java {
        targetExclude("build/generated-src/**", "build/generated/**")
    }
}
